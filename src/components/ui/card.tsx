import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean }
>(({ className, interactive, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[var(--r-lg)] border border-[var(--line)] bg-[var(--surface)] p-5 md:p-6 shadow-[var(--shadow-hair)]",
      interactive && "transition-colors hover:border-[var(--line-strong)] cursor-pointer",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

